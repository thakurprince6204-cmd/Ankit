// Helper to look up a term by ID
export const getTermById = (id: string): DictionaryTerm | undefined => {
  return DICTIONARY_TERMS.find(t => t.id === id);
};

// Helper to get all terms for an education level
export const getTermsByLevel = (level: string): DictionaryTerm[] => {
  if (level === 'All') return DICTIONARY_TERMS;
  return DICTIONARY_TERMS.filter(t => t.level.includes(level as any));
};

// Helper to get terms by category
export const getTermsByCategory = (category: Category | 'All'): DictionaryTerm[] => {
  if (category === 'All') return DICTIONARY_TERMS;
  return DICTIONARY_TERMS.filter(t => t.category === category);
};
